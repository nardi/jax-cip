"""Writes `src/jaxcip/_scip_parameters.py` from the parameter table of the linked SCIP.

Run `uv run python scripts/generate_scip_parameters.py` and then `uv run ruff format` after
changing the SCIP version.
"""

import re
import textwrap
from pathlib import Path

from jaxcip._problem import parameter_table, scip_version

TARGET = Path(__file__).parent.parent / "src" / "jaxcip" / "_scip_parameters.py"

HEADER = '''"""The parameters of SCIP {version}, generated by `scripts/generate_scip_parameters.py`."""

from enum import Enum

from jaxcip._types import ParameterType


class ScipParameter(Enum):
    """A parameter of SCIP with its default plugins, named after its path.

    `NUMERICS_FEASTOL` is the parameter `numerics/feastol`. The docstring of each member is
    SCIP's description.
    """

    def __init__(self, path: str, parameter_type: ParameterType) -> None:
        self.path = path
        """Name of the parameter in SCIP."""
        self.parameter_type = parameter_type
        """Type of the parameter's values."""
'''


def member_name(path: str) -> str:
    """Returns the enum member name of a parameter path."""
    return re.sub(r"[^0-9A-Za-z]+", "_", path).strip("_").upper()


def docstring(description: str) -> str:
    """Returns a parameter description as an indented attribute docstring."""
    text = " ".join(description.split()).replace("\\", "\\\\").replace('"""', "'''")
    text = text[0].upper() + text[1:] if text else "No description."
    if not text.endswith((".", "?", "!")):
        text += "."
    lines = textwrap.wrap(text, 88 - 7, break_on_hyphens=False)
    if len(lines) == 1:
        return f'    """{lines[0]}"""\n'
    body = "\n".join(f"    {line}" for line in lines)
    return f'    """\n{body}\n    """\n'


def main() -> None:
    version = scip_version()
    names: set[str] = set()
    parts = [
        HEADER.format(version=f"{version.major}.{version.minor}.{version.technical}")
    ]
    for path, parameter_type, description in sorted(parameter_table()):
        name = member_name(path)
        if name in names:
            raise ValueError(f"Two parameters map to the member name {name}")
        names.add(name)
        parts.append(
            f'\n    {name} = ("{path}", ParameterType.{parameter_type.name})\n'
        )
        parts.append(docstring(description))
    TARGET.write_text("".join(parts))


if __name__ == "__main__":
    main()
